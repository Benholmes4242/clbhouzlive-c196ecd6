import React from 'react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { cleanup, render, screen } from '@testing-library/react';
const f = vi.hoisted(() => ({ ready: {} as Record<string, boolean>, user: null as { id: string } | null }));
const section = vi.hoisted(() => async (id: string) => { const { useSectionReady } = await import('@/components/courses/browse/PageLoadGate'); return () => { useSectionReady(id, f.ready[id] === true); return <div data-testid={id} />; }; });
vi.mock('@/hooks/useSupabaseSession', () => ({ useSupabaseSession: () => ({ user: f.user, loading: false }) }));
vi.mock('@/components/courses/useStatBrowse', () => ({ useCourseBrowseTruth: () => ({ data: null, isFetched: f.ready.figures }) }));
vi.mock('@/components/courses/useBrowseReviews', () => ({ useBrowseReviews: () => ({ pool: [], isPending: !f.ready.latestReviews }) }));
vi.mock('@/stores/reviewSheetStore', () => ({ useReviewSheetStore: () => vi.fn() }));
vi.mock('@/components/courses/CourseMasthead', () => ({ HERO_FIGURE_LABEL: {}, HERO_FIGURE_VALUE: {} }));
vi.mock('@/components/courses/browse/sectionShells', () => ({ WhoPlayingShell: () => <div data-testid="who-shell" />, ByRegionShell: () => <div data-testid="region-shell" />, LatestCoursesShell: () => <div data-testid="courses-shell" />, FiguresRowShell: () => null }));
vi.mock('@/components/courses/StatBrowse', async () => ({ default: await section('list') }));
vi.mock('@/components/courses/browse/WhoPlayingSection', async () => ({ WhoPlayingSection: await section('whoPlaying') }));
vi.mock('@/components/courses/browse/ByRegionSection', async () => ({ ByRegionSection: await section('byRegion'), ALL_COURSES_ANCHOR: 'all-courses' }));
vi.mock('@/components/courses/browse/LatestCoursesSection', async () => ({ LatestCoursesSection: await section('latestCourses') }));
vi.mock('@/components/courses/browse/MostPlayedSection', async () => ({ MostPlayedSection: await section('mostPlayed') }));
vi.mock('@/components/courses/browse/HardestSection', async () => ({ HardestSection: await section('hardest') }));
vi.mock('@/components/courses/browse/LatestHolesSection', async () => ({ LatestHolesSection: await section('latestHoles') }));
vi.mock('@/components/courses/browse/LatestReviewsSection', () => ({ LatestReviewsSection: () => null }));
import CoursesBrowsePage from '@/components/courses/CoursesBrowsePage';
const tree = () => <CoursesBrowsePage onOpenDirectory={() => {}} />;
beforeEach(() => { f.ready = {}; f.user = null; });
afterEach(cleanup);
it('holds the list and all sections together until the list is ready, preserving the list outside section bleed', () => {
  f.user = { id: 'u' };
  const view = render(tree());
  expect(screen.getByTestId('who-shell')).toBeVisible();
  expect(screen.getByTestId('region-shell')).toBeVisible();
  expect(screen.getByTestId('courses-shell')).toBeVisible();
  for (const id of ['whoPlaying', 'byRegion', 'latestCourses', 'mostPlayed', 'hardest', 'latestHoles', 'list']) expect(screen.getByTestId(id)).not.toBeVisible();
  f.ready = Object.fromEntries(['whoPlaying', 'byRegion', 'latestCourses', 'mostPlayed', 'hardest', 'latestHoles', 'latestReviews', 'figures'].map(id => [id, true]));
  view.rerender(tree());
  expect(screen.getByTestId('list')).not.toBeVisible();
  f.ready.list = true; view.rerender(tree());
  expect(screen.queryByTestId('region-shell')).toBeNull();
  expect(screen.getByTestId('list')).toBeVisible();
  expect(screen.getByTestId('list').parentElement).toBe(screen.getByTestId('byRegion').parentElement?.parentElement);
});
it('the signed-out fallback omits the circle shell', () => { render(tree()); expect(screen.queryByTestId('who-shell')).toBeNull(); expect(screen.getByTestId('region-shell')).toBeVisible(); expect(screen.getByTestId('courses-shell')).toBeVisible(); });
